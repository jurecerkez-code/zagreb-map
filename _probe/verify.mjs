import { chromium } from '@playwright/test';
const b = await chromium.launch();
const pg = await (await b.newContext({ viewport: { width: 1600, height: 900 } })).newPage();
const errs = [];
pg.on('console', m => { const t = m.text(); if (/streets|did not load|error/i.test(t)) errs.push(t.slice(0, 140)); });
await pg.goto('https://jurecerkez-code.github.io/zagreb-map/', { waitUntil: 'domcontentloaded', timeout: 60000 });
await pg.waitForTimeout(70000);
const count = await pg.evaluate(() => (document.body.innerText.match(/\d[\d.\s]*?\s*zgrada/i) || ['?'])[0]);
const roadsOk = await pg.evaluate(() => fetch('data/v20261103-fix/roads.json').then(r => r.status).catch(() => 'fetch-fail'));
console.log(JSON.stringify({ count, roadsOk, errs: errs.slice(0, 6) }));
await pg.evaluate(() => { if (typeof startRide === 'function') startRide(); });
await pg.waitForTimeout(6000);
await pg.screenshot({ path: '_probe/live_ride_after.png', timeout: 90000 }).catch(e => console.log('shot fail', String(e).slice(0,80)));
console.log('done');
await b.close();
